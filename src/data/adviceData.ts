export const generateAdvice = (
  mbti: MBTIType,
  relationship: RelationshipType,
  situationId: string
): CommunicationAdvice => {
  const adviceMap = getAdviceForMBTI(mbti);

  return {
    mbti,
    relationship,
    situation: situationId,
    overview: adviceMap.overview[relationship],
    keyPoints: adviceMap.keyPoints,
    communicationStyle: {
      tone: adviceMap.tone[relationship],
      approach: adviceMap.approach[relationship],
      avoid: adviceMap.avoid
    },
    examples: adviceMap.examples[relationship],
    tips: adviceMap.tips[relationship]
  };
};

